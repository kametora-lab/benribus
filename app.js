function showSavedRoutesStatus() {
  if (!savedRoutes.length) {
    setSavedRouteStatus("まだ保存された経路はありません。");
    return;
  }
  const first = routeFromRecord(savedRoutes[0]);
  if (!first) {
    setSavedRouteStatus(`${savedRoutes.length}件の経路履歴を保存しています。`);
    return;
  }
  setSavedRouteStatus(`最近の経路: ${first.from.name} → ${first.to.name}（${savedRoutes.length}/5件）`);
}

async function saveSelectedRoute(route) {
  if (!route || route.key === lastSavedRouteKey) return;
  lastSavedRouteKey = route.key;
  const nextRoute = {
    key: route.key,
    fromId: String(route.from.id),
    toId: String(route.to.id),
    savedAt: new Date().toISOString()
  };
  savedRoutes = [nextRoute, ...savedRoutes.filter((saved) => saved.key !== route.key)].slice(0, MAX_SAVED_ROUTES);
  renderSavedRoutes();
  showSavedRoutesStatus();
  try {
    await writeRouteHistory(savedRoutes);
  } catch {
    setSavedRouteStatus("このブラウザでは経路履歴を保存できませんでした。");
  }
}

async function deleteSavedRoute(routeKey) {
  savedRoutes = savedRoutes.filter((route) => route.key !== routeKey);
  if (lastSavedRouteKey === routeKey) lastSavedRouteKey = "";
  renderSavedRoutes();
  showSavedRoutesStatus();
  try {
    await writeRouteHistory(savedRoutes);
  } catch {
    setSavedRouteStatus("経路履歴を削除できませんでした。");
  }
}

function applyRoute(from, to, options = {}) {
  selectStop("from", from, { save: false });
  selectStop("to", to, { save: options.save !== false });
}

async function restoreSavedRoutes() {
  try {
    const stored = await readStoredRouteData();
    const history = Array.isArray(stored.history?.routes) ? stored.history.routes : [];
    const migratedLastRoute = stored.lastRoute
      ? [{ ...stored.lastRoute, key: `${stored.lastRoute.fromId}-${stored.lastRoute.toId}` }]
      : [];
    savedRoutes = [...history, ...migratedLastRoute]
      .filter((route) => route?.fromId && route?.toId)
      .filter((route, index, routes) => routes.findIndex((item) => item.key === route.key) === index)
      .slice(0, MAX_SAVED_ROUTES);
    renderSavedRoutes();
    showSavedRoutesStatus();

    const latest = routeFromRecord(savedRoutes[0] || {});
    if (latest) {
      lastSavedRouteKey = latest.key;
      applyRoute(latest.from, latest.to, { save: false });
    }
    if (migratedLastRoute.length && !history.length) await writeRouteHistory(savedRoutes);
  } catch {
    renderSavedRoutes();
    setSavedRouteStatus("経路履歴を読み込めませんでした。");
  }
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = "";
  let inQuotes = false;
  const source = String(text || "").replace(/^\ufeff/, "");

  for (let index = 0; index < source.length; index += 1) {
    const char = source[index];
    const next = source[index + 1];
    if (char === '"' && inQuotes && next === '"') {
      cell += '"';
      index += 1;
    } else if (char === '"') {
      inQuotes = !inQuotes;
    } else if (char === "," && !inQuotes) {
      row.push(cell);
      cell = "";
    } else if ((char === "\n" || char === "\r") && !inQuotes) {
      if (char === "\r" && next === "\n") index += 1;
      row.push(cell);
      if (row.some((value) => value.trim())) rows.push(row);
      row = [];
      cell = "";
    } else {
      cell += char;
    }
  }

  row.push(cell);
  if (row.some((value) => value.trim())) rows.push(row);
  return rows;
}

function stopsFromCsv(text) {
  const rows = parseCsv(text);
  if (rows.length < 2) return [];
  const headers = rows[0].map((header) => header.trim());
  const indexOf = (...names) => names.map((name) => headers.indexOf(name)).find((index) => index >= 0);
  const timetableIndex = indexOf("時刻表", "timetable");
  const nameIndex = indexOf("バス亭名", "バス停名", "name");
  const mapIndex = indexOf("のりば地図", "map");
  const idIndex = indexOf("ID", "id");
  const fareIndex = indexOf("(乗車)", "運賃", "fare");

  return rows.slice(1).map((row) => {
    const rawId = row[idIndex] ?? "";
    const id = Math.trunc(Number.parseFloat(String(rawId).replace(/[^\d.]/g, "")));
    const name = (row[nameIndex] ?? "").trim();
    if (!id || !name) return null;
    return {
      id,
      name,
      timetable: (row[timetableIndex] ?? `https://shimabus.busplus.jp/signage/${id}`).trim(),
      map: (row[mapIndex] ?? "").trim(),
      fare: (row[fareIndex] ?? "").trim()
    };
  }).filter(Boolean);
}

async function loadStopsFromCsvFile(showAlert = false) {
  try {
    const response = await fetchFirstCsv();
    const buffer = await response.arrayBuffer();
    const csvText = decodeCsvBuffer(buffer);
    const stops = stopsFromCsv(csvText);
    if (!stops.length) throw new Error("CSVに有効なバス停がありません");
    BUS_STOPS = stops;
    INITIAL_BUS_STOPS = stops.map((stop) => ({ ...stop }));
    afterStopsChanged();
    elements.csvStatus.textContent = `${response.csvName} から ${stops.length}件を読み込みました。`;
    if (showAlert) alert("バス停.csv を再読み込みしました。");
  } catch (error) {
    BUS_STOPS = EMBEDDED_BUS_STOPS.map((stop) => ({ ...stop }));
    INITIAL_BUS_STOPS = BUS_STOPS.map((stop) => ({ ...stop }));
    afterStopsChanged();
    elements.csvStatus.textContent = `自動読込に失敗しました。内蔵データ ${BUS_STOPS.length}件を使っています。必要なら「CSVを選択」から取り込んでください。`;
    if (showAlert) alert(`バス停.csv を読み込めませんでした。CSVを選択から取り込んでください。\n${error.message}`);
  }
}

async function loadStopsFromPickedFile(file) {
  if (!file) return;
  try {
    const buffer = await file.arrayBuffer();
    const stops = stopsFromCsv(decodeCsvBuffer(buffer));
    if (!stops.length) throw new Error("CSVに有効なバス停がありません");
    BUS_STOPS = stops;
    INITIAL_BUS_STOPS = stops.map((stop) => ({ ...stop }));
    afterStopsChanged();
    elements.csvStatus.textContent = `${file.name} から ${stops.length}件を取り込みました。`;
  } catch (error) {
    alert(`CSVを取り込めませんでした: ${error.message}`);
  } finally {
    elements.csvFileInput.value = "";
  }
}

async function fetchFirstCsv() {
  const cacheBust = `ts=${Date.now()}`;
  const candidates = [
    ["バス停.csv", `./${encodeURIComponent("バス停.csv")}?${cacheBust}`],
    ["バス停.csv", `./バス停.csv?${cacheBust}`],
    ["bus-stops.csv", `./bus-stops.csv?${cacheBust}`]
  ];
  const failures = [];

  for (const [csvName, url] of candidates) {
    try {
      const response = await fetch(url, { cache: "no-store" });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      response.csvName = csvName;
      return response;
    } catch (error) {
      failures.push(`${csvName}: ${error.message}`);
    }
  }

  throw new Error(failures.join(" / "));
}

function decodeCsvBuffer(buffer) {
  const decoders = ["utf-8", "shift_jis"];
  for (const encoding of decoders) {
    try {
      const text = new TextDecoder(encoding).decode(buffer);
      if (text.includes("時刻表") && (text.includes("バス亭名") || text.includes("バス停名"))) {
        return text;
      }
    } catch {
      // Try the next browser-supported encoding.
    }
  }
  return new TextDecoder("utf-8").decode(buffer);
}

